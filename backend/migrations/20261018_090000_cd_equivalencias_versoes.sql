create function public.cd_validar_equivalencia_versao() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 if not exists(select 1 from public.cd_conclusoes c
 join public.cd_curriculos origem on origem.igreja_id=c.igreja_id and origem.id=c.curriculo_id
 join public.cd_modulos om on om.igreja_id=c.igreja_id and om.id=c.modulo_id
 join public.cd_curriculos destino on destino.igreja_id=c.igreja_id and destino.id=new.curriculo_id
 join public.cd_modulos dm on dm.igreja_id=destino.igreja_id and dm.curriculo_id=destino.id and dm.id=new.modulo_id
 where c.igreja_id=new.igreja_id and c.id=new.conclusao_origem_id and c.pessoa_id=new.pessoa_id
 and not c.revogada and origem.id<>destino.id and origem.familia_id=destino.familia_id
 and origem.ordem_versao<destino.ordem_versao and om.numero=dm.numero for share of c)
 then raise exception 'Conclusão de origem incompatível ou revogada' using errcode='23514'; end if;
 return new;
end $$;
revoke all on function public.cd_validar_equivalencia_versao() from public,anon,authenticated,service_role;
create trigger cd_equivalencia_valida before insert on public.cd_equivalencias_versoes
 for each row execute function public.cd_validar_equivalencia_versao();
