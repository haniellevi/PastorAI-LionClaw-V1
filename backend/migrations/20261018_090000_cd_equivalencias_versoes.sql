-- Decision 6 (18/10): a registered equivalence carries prior learning forward.
set local lock_timeout = '2s';
-- Legacy schema had exactly one CD catalog per church (unique igreja/versao).
-- Preserve that implicit family under its oldest curriculum UUID. New families
-- use their first curriculum UUID; explicit new versions inherit familia_id.
-- A monotonic insertion order, rather than editable version labels or now()
-- (which ties within a transaction), defines earlier/later versions.
alter table public.cd_curriculos add column ordem_versao bigint generated by default as identity;
-- Identity generation needs no direct sequence grant; tenants cannot rewind it.
revoke all on sequence public.cd_curriculos_ordem_versao_seq from public,anon,authenticated,service_role;
with ordered as (select id,row_number() over(order by criada_em,id) as position from public.cd_curriculos)
update public.cd_curriculos c set ordem_versao=o.position from ordered o where o.id=c.id;
alter table public.cd_curriculos add column familia_id uuid;
update public.cd_curriculos c set familia_id=(select first_value(id) over(order by criada_em,id)
 from public.cd_curriculos root where root.igreja_id=c.igreja_id limit 1);
alter table public.cd_curriculos alter column familia_id set not null;
alter table public.cd_curriculos add foreign key(igreja_id,familia_id) references public.cd_curriculos(igreja_id,id);
grant insert(familia_id) on public.cd_curriculos to authenticated;
-- Keep legacy inserts compatible: without an explicit predecessor this is an
-- independent family. Names are editable and never identify a family.
create function public.cd_familia_inicial() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 new.familia_id := coalesce(new.familia_id,new.id);
 return new;
end $$;
revoke all on function public.cd_familia_inicial() from public,anon,authenticated,service_role;
create trigger cd_familia_inicial before insert on public.cd_curriculos
 for each row execute function public.cd_familia_inicial();
alter table public.cd_conclusoes add column revogada boolean not null default false;
-- A no-op identity UPDATE grant permits PostgreSQL row locks; a guard prevents
-- identity/content edits. Revocation itself has no application UPDATE grant.
grant update(id) on public.cd_conclusoes to authenticated;
create function public.cd_conclusao_imutavel() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 if (to_jsonb(new)-'revogada')<>(to_jsonb(old)-'revogada') then
   raise exception 'Conclusão imutável' using errcode='23514';
 end if;
 return new;
end $$;
revoke all on function public.cd_conclusao_imutavel() from public,anon,authenticated,service_role;
create trigger cd_conclusao_imutavel before update on public.cd_conclusoes
 for each row execute function public.cd_conclusao_imutavel();
-- No application grant to revoke/restore conclusions: reserved for an explicit
-- future maintenance workflow. Every consumer below checks the live state.
alter table public.cd_conclusoes add constraint cd_conclusao_pessoa_key unique(igreja_id,id,pessoa_id);
alter table public.cd_matriculas add column concluida boolean not null default false;
-- Backfill before installing the derived-field guard. Completed rows stay frozen.
alter table public.cd_matriculas disable trigger cd_matricula_concluida;
update public.cd_matriculas m set concluida=true where exists(select 1 from public.cd_conclusoes c
 where c.igreja_id=m.igreja_id and c.matricula_id=m.id);
alter table public.cd_matriculas enable trigger cd_matricula_concluida;
create or replace function public.cd_preservar_conclusao() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
declare mid uuid; finished boolean;
begin
 if TG_TABLE_NAME='cd_matriculas' then mid := new.id; else mid := new.matricula_id; end if;
 finished := exists(select 1 from public.cd_conclusoes c where c.igreja_id=new.igreja_id and c.matricula_id=mid);
 if TG_TABLE_NAME='cd_matriculas' then
   -- The caller cannot forge this projection, even with its column grant.
   new.concluida := finished;
   if TG_OP='INSERT' then return new; end if;
   if finished and not old.concluida and
      (to_jsonb(new)-'concluida')=(to_jsonb(old)-'concluida') then return new; end if;
 end if;
 if finished then raise exception 'Matrícula concluída' using errcode='23514'; end if;
 return new;
end $$;
create trigger cd_matricula_estado before insert on public.cd_matriculas
 for each row execute function public.cd_preservar_conclusao();
create function public.cd_finalizar_matricula() returns trigger
language plpgsql set search_path=pg_catalog,public as $$
begin
 update public.cd_matriculas set concluida=true where igreja_id=new.igreja_id and id=new.matricula_id;
 return new;
end $$;
revoke all on function public.cd_finalizar_matricula() from public,anon,authenticated,service_role;
grant update(concluida) on public.cd_matriculas to authenticated;
create trigger cd_conclusao_finaliza after insert on public.cd_conclusoes
 for each row execute function public.cd_finalizar_matricula();
drop index public.cd_matriculas_ativa_modulo;
create unique index cd_matriculas_ativa_modulo on public.cd_matriculas(igreja_id,pessoa_id,modulo_numero) where ativa and not concluida;

