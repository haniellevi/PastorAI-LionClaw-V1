-- The caller's RLS applies to every source. Equivalence is live, certificate
-- links are immutable snapshots and do not silently rewrite issued documents.
create view public.cd_cumprimentos with (security_invoker=true) as
 select c.igreja_id,c.pessoa_id,c.curriculo_id,c.modulo_id,c.id,'conclusao'::text as tipo
 from public.cd_conclusoes c where not c.revogada
 union all
 select e.igreja_id,e.pessoa_id,e.curriculo_id,e.modulo_id,e.id,'equivalencia'::text
 from public.cd_equivalencias_versoes e
 join public.cd_conclusoes c on c.igreja_id=e.igreja_id and c.id=e.conclusao_origem_id and c.pessoa_id=e.pessoa_id
 join public.cd_curriculos o on o.igreja_id=c.igreja_id and o.id=c.curriculo_id
 join public.cd_curriculos d on d.igreja_id=e.igreja_id and d.id=e.curriculo_id
 where not c.revogada and o.familia_id=d.familia_id;
revoke all on public.cd_cumprimentos from public,anon,authenticated,service_role;
grant select on public.cd_cumprimentos to authenticated;
