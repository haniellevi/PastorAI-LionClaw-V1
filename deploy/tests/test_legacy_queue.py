def test_full_rehearsal_real_entrypoint_and_cleanup():
    fake = FakeDocker()
    r = rehearsal(fake)
    legacy.rehearse(r)
    assert r.checks == [
        'legacy-source-exact-git-blobs-07a3f4d (sem .env no workdir)', 'runtime-matches-requirements.lock',
        'real-entrypoint-ready-heartbeat-lease-registry',
        'sigterm-exit-0-heartbeat-stopped-lease-and-registry-removed',
        'real-webhookqueue-enqueue-of-parser-ignored-event-survives-while-stopped',
        'restart-same-container-new-worker-id-consumed-and-acked-ignored-event',
        'second-sigterm-exit-0-heartbeat-stopped-deregistered']
    assert len(fake.worker_ids) == 2 and len(set(fake.worker_ids)) == 2
    worker_runs = [c for c in fake.calls if c[1] == 'run' and c[-2:] == legacy.ENTRY]
    assert len(worker_runs) == 1 and worker_runs[0][-3] == LEGACY  # um container, reiniciado por start
    argv = worker_runs[0]
    env = dict(argv[i + 1].split('=', 1) for i, a in enumerate(argv) if a == '--env')
    assert env == legacy.SYNTHETIC_ENV and env['ALLOW_REAL_SENDS'] == 'false'
    assert not any('KEY' in name or 'SECRET' in name or 'TOKEN' in name for name in env)
    assert [c[2] for c in fake.calls if c[1] == 'start'] == [r.ids[legacy.WORKER]]
    assert {c[1] for c in fake.calls} <= {'context', 'image', 'network', 'run', 'ps', 'inspect', 'kill',
                                          'start', 'wait', 'logs', 'exec', 'rm', 'container'}
    assert r.cleanup() == dict(status='clean', errors=[], leftovers=dict(containers=[], networks=[]))
    assert not fake.containers and not fake.networks


@pytest.mark.parametrize('knob, value, code', [
    ('term_exit', 1, 'ungraceful-exit'),
    ('leave_registry', True, 'not-deregistered'),
    ('consume', 'dead', 'unexpected-queue-state'),
    ('consume', 'none', 'ignored-event-not-acked'),
    ('parse_ignores', False, 'ignored-payload'),
    ('crash_on_start', True, 'worker-exited-before-ready'),
    ('late', lambda redis, wid: redis.update({'pastorai:webhooks:dead': ['x']}), 'unstable-after-ack'),
    ('late', lambda redis, wid: redis.update({'outra:chave': 'x'}), 'unstable-after-ack'),  # fora do prefixo
    ('late', lambda redis, wid: redis.pop(legacy.LEASE + wid), 'unstable-after-ack'),
])
def test_worker_contract_violations_fail_and_cleanup(knob, value, code):
    fake = FakeDocker()
    setattr(fake, knob, value)
    r = rehearsal(fake)
    refused(code, lambda: legacy.rehearse(r))
    assert r.cleanup()['status'] == 'clean' and not fake.containers and not fake.networks


@pytest.mark.parametrize('mutate, code', [
    (lambda f: f.runtime['dists'].update(redis='6.0.0'), 'runtime-mismatch'),
    (lambda f: f.runtime.update(python=[3, 12]), 'runtime-mismatch'),
    (lambda f: f.runtime.update(files={}, rejected=['.env']), 'source-mismatch'),
    (lambda f: f.runtime.update(files={}, missing=['requirements.lock']), 'source-mismatch'),
    (lambda f: f.runtime['files'].update({'requirements.lock': '0' * 64}), 'source-mismatch'),
    (lambda f: f.images[LEGACY]['Config']['Env'].append('DATABASE_URL=x'), 'image-env'),
    (lambda f: f.images[LEGACY]['Config']['Env'].append('PIP_INDEX_URL=x'), 'image-env'),  # sem prefixo
    (lambda f: f.images[LEGACY]['Config'].update(Volumes={'/x': {}}), 'image-volumes'),
    (lambda f: f.images.pop(LEGACY), 'image-not-local-immutable'),
])
def test_preflight_refusals_before_any_network_or_worker(mutate, code):
    fake = FakeDocker()
    mutate(fake)
    r = rehearsal(fake)
    refused(code, lambda: legacy.rehearse(r))
    assert r.phase == 'preflight'
    assert not any(c[1] == 'network' and c[2] == 'create' for c in fake.calls)
    assert not any(c[-2:] == legacy.ENTRY for c in fake.calls if c[1] == 'run')
    assert r.cleanup()['status'] == 'clean' and not fake.containers


