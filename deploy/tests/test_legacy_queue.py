# -- probe de runtime executado de verdade (Python local, sem Docker) -----
AUDIT = (
    "import sys\n"
    "def _audit(event, args):\n"
    "    if event == 'open' and isinstance(args[0], str):\n"
    "        sys.stderr.write('OPEN ' + args[0] + '\\n')\n"
    "sys.addaudithook(_audit)\n"
)


def _run_probe(root):
    done = subprocess.run([sys.executable, '-I', '-c', AUDIT + legacy.RUNTIME_PROBE, str(root), '[]',
                           json.dumps(sorted(FILES))], capture_output=True, text=True, timeout=30)
    assert done.returncode == 0, done.stderr
    prefix = str(root) + os.sep
    opened = {line[5:].removeprefix(prefix) for line in done.stderr.splitlines()
              if line.startswith('OPEN ' + prefix)}
    return json.loads(done.stdout.splitlines()[-1]), opened


def _source_tree(root):
    for rel, data in FILES.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_bytes(data)


def test_runtime_probe_hashes_only_approved_regular_files(tmp_path):
    _source_tree(tmp_path)
    observed, opened = _run_probe(tmp_path)
    assert observed['files'] == legacy.manifest(FILES) and opened == set(FILES)
    assert observed['rejected'] == [] and observed['missing'] == []


@pytest.mark.skipif(os.geteuid() == 0, reason='root ignora permissões de diretório')
def test_runtime_probe_unreadable_directory_fails_closed(tmp_path):
    _source_tree(tmp_path)
    locked = tmp_path / 'app' / 'workers'
    locked.chmod(0)
    try:
        observed, opened = _run_probe(tmp_path)
    finally:
        locked.chmod(0o755)
    assert 'unreadable:app/workers' in observed['rejected']
    assert observed['files'] == {} and opened == set()


def test_runtime_probe_rejects_unexpected_paths_without_opening_anything(tmp_path):
    _source_tree(tmp_path)
    (tmp_path / '.env').write_text('PROTEGIDO=1\n')
    (tmp_path / 'app' / 'secrets').mkdir()
    (tmp_path / 'app' / 'secrets' / 'k.py').write_text('PROTEGIDO\n')
    (tmp_path / 'app' / 'link.py').symlink_to('../.env')
    os.mkfifo(tmp_path / 'app' / 'pipe')  # abrir para leitura bloquearia: o timeout acusaria
    (tmp_path / 'requirements.lock').unlink()
    (tmp_path / 'requirements.lock').symlink_to('.env')  # caminho esperado, mas link
    observed, opened = _run_probe(tmp_path)
    assert opened == set()  # nem os aprovados são abertos quando há rejeição
    assert observed['files'] == {} and observed['missing'] == ['requirements.lock']
    assert observed['rejected'] == sorted(['.env', 'app/secrets', 'app/link.py', 'app/pipe', 'requirements.lock'])


# -- requirements.lock ----------------------------------------------------
def test_lock_entries_and_runtime_correspondence():
    assert legacy.lock_entries(LOCK) == [['redis', '7.0.1', None],
                                         ['colorama', '0.4.6', "sys_platform == 'win32'"],
                                         ['sqlalchemy', '2.0.49', None]]
    assert legacy.lock_python(LOCK) == [3, 13]
    good = FakeDocker().runtime
    assert legacy.runtime_mismatch(LOCK, good) == {}
    assert legacy.runtime_mismatch(LOCK, dict(good, duplicates=['redis'])) == {'duplicates': ['redis']}
    bad = dict(good, python=[3, 12], dists={'redis': '6.0.0', 'pip': '25.0', 'requests': '2.0'}, applicable={})
    assert legacy.runtime_mismatch(LOCK, bad) == {
        'python': [3, 12], 'wrong_version': ['redis'], 'missing': ['sqlalchemy'], 'extra': ['requests'],
        'unevaluated_markers': ["sys_platform == 'win32'"]}
    refused('lock-format', lambda: legacy.lock_entries('pacote[extra]==1.0\n'))


