import json
import os
import subprocess
import sys
import uuid
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import rehearse_legacy_containment as containment  # noqa: E402
import rehearse_legacy_queue as legacy  # noqa: E402

LEGACY = 'sha256:' + 'a' * 64
REDIS = 'sha256:' + 'b' * 64
LOCK = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv pip compile requirements.txt --universal --python-version 3.13 --generate-hashes\n"
    "redis==7.0.1 \\\n    --hash=sha256:aaaa\n    # via -r requirements.txt\n"
    "colorama==0.4.6 ; sys_platform == 'win32' \\\n    --hash=sha256:bbbb\n"
    "SQLAlchemy==2.0.49 \\\n    --hash=sha256:cccc\n"
)
FILES = {'app/__init__.py': b'', 'app/workers/queue_worker.py': b'# legado\n',
         'requirements.lock': LOCK.encode()}
VALUED = {'--pull', '--restart', '--network', '--network-alias', '--entrypoint', '--user', '--cap-drop',
          '--security-opt', '--pids-limit', '--workdir', '--tmpfs', '--label', '--env', '--name'}
FORBIDDEN = {'-p', '--publish', '-P', '--publish-all', '-v', '--volume', '--mount', '--privileged'}


@pytest.fixture(autouse=True)
def local_docker(monkeypatch):
    for name in containment.REMOTE_ENV:
        monkeypatch.delenv(name, raising=False)


class FakeDocker:
    def __init__(self):
        self.images = {LEGACY: dict(Id=LEGACY, Config=dict(Env=['PATH=/usr/local/bin:/usr/bin', 'LANG=C.UTF-8'])),
                       REDIS: dict(Id=REDIS, Config=dict(Env=[], Volumes={'/data': {}}))}
        self.containers, self.networks, self.calls, self.redis, self.worker_ids = {}, {}, [], {}, []
        self.runtime = dict(python=[3, 13], files=legacy.manifest(FILES), rejected=[], missing=[], duplicates=[],
                            dists={'redis': '7.0.1', 'sqlalchemy': '2.0.49', 'pip': '25.0'},
                            applicable={"sys_platform == 'win32'": False})
        self.parse_ignores, self.term_exit, self.leave_registry = True, 0, False
        self.consume, self.crash_on_start = 'ack', False
        self.late, self.keys_after_restart, self.os_error_on = None, 0, None

    def __call__(self, argv):
        self.calls.append(argv)
        assert argv[0] == 'docker'
        command, args = argv[1], argv[2:]
        if (command, args[0]) == self.os_error_on:
            raise OSError('simulado')
        if command == 'context':
            return json.dumps([{'Endpoints': {'docker': {'Host': 'unix:///var/run/docker.sock'}}}])
        if command == 'image':
            if args[1] not in self.images:
                raise containment.Refused('docker-step')
            return json.dumps([self.images[args[1]]])
        if command == 'network':
            return self._network(args)
        if command == 'run':
            return self._run(args)
        if command == 'container':
            return '\n'.join(self.containers)
        if command == 'ps':
            name, value = args[args.index('--filter') + 1].removeprefix('label=').split('=', 1)
            return '\n'.join(cid for cid, c in self.containers.items() if c['Config']['Labels'].get(name) == value)
        if command == 'inspect':
            if args[0] not in self.containers:
                raise containment.Refused('docker-step')
            return json.dumps([{k: v for k, v in self.containers[args[0]].items() if k not in ('kind', 'out')}])
        if command == 'kill':
            assert args[:2] == ['--signal', 'SIGTERM'], 'somente SIGTERM'
            self._term(self.containers[args[2]])
            return ''
        if command == 'start':
            self._boot(self.containers[args[0]])
            return ''
        if command == 'wait':
            return self._probe(self.containers[args[0]])
        if command == 'logs':
            return self.containers[args[0]]['out']
        if command == 'exec':
            assert args[1] == 'redis-cli' and self.containers[args[0]]['kind'] == 'redis'
            return self._redis_cli(*args[2:])
        if command == 'rm':
            self.containers.pop(args[-1])
            return ''
        raise AssertionError(f'comando inesperado: {command}')

    def _network(self, args):
        if args[0] == 'create':
            assert '--internal' in args
            nid = uuid.uuid4().hex * 2
            labels = dict(args[i + 1].split('=', 1) for i, a in enumerate(args) if a == '--label')
            self.networks[nid] = dict(name=args[-1], Labels=labels)
            return nid
        if args[0] == 'ls':
            return '\n'.join(self.networks)
        if args[0] == 'inspect':
            net = self.networks[args[1]]
            attached = {cid: {} for cid, c in self.containers.items()
                        if c['HostConfig']['NetworkMode'] == args[1] and c['State']['Running']}
            return json.dumps([dict(Id=args[1], Name=net['name'], Internal=True, Labels=net['Labels'],
                                    Containers=attached)])
        if args[0] == 'rm':
            self.networks.pop(args[1])
            return ''
        raise AssertionError(args)

    def _run(self, args):
        opts, labels, env, i = {}, {}, [], 0
        while args[i].startswith('-'):
            flag = args[i]
            assert flag not in FORBIDDEN
            if flag in VALUED:
                value, i = args[i + 1], i + 2
                if flag == '--label':
                    labels.update([value.split('=', 1)])
                elif flag == '--env':
                    env.append(value)
                else:
                    opts[flag] = value
            else:
                opts[flag], i = True, i + 1
        image, command = args[i], args[i + 1:]
        assert opts['--pull'] == 'never' and opts['--restart'] == 'no' and opts['--read-only']
        assert opts['--cap-drop'] == 'ALL' and opts['--user'] == containment.USER
        if image not in self.images:
            raise containment.Refused('docker-step')
        network = opts['--network']
        kind = 'redis' if opts['--entrypoint'] == 'redis-server' else (
            'worker' if command == legacy.ENTRY else 'probe')
        cid = uuid.uuid4().hex * 2
        image_env = self.images[image]['Config']['Env']
        self.containers[cid] = container = dict(
            Id=cid, Image=image, Path=opts['--entrypoint'], Args=command, RestartCount=0, kind=kind, out='',
            Config=dict(Labels=labels, Env=[*image_env, *env], Entrypoint=[opts['--entrypoint']], Cmd=command,
                        User=opts['--user'], WorkingDir=opts.get('--workdir', '/')),
            HostConfig=dict(PortBindings={}, PublishAllPorts=False, Privileged=False, Binds=None,
                            NetworkMode=network, ReadonlyRootfs=True),
            Mounts=[], NetworkSettings=dict(Ports={}, Networks={self.networks[network]['name']: {}}
                                            if network in self.networks else {}),
            State=dict(Running=True, ExitCode=0))
        if kind == 'worker':
            self._boot(container)
        return cid

    # -- contrato observável do worker legado --------------------------------
    def _boot(self, container):
        container['State'] = dict(Running=True, ExitCode=0)
        if self.crash_on_start:
            container['State'] = dict(Running=False, ExitCode=1)
            return
        wid = uuid.uuid4().hex
        self.worker_ids.append(wid)
        container['wid'] = wid
        self.redis[legacy.LEASE + wid] = wid
        self.redis.setdefault(legacy.REGISTRY, set()).add(wid)
        self.redis[legacy.HEARTBEAT] = 'ready'
        pending = self.redis.pop(legacy.QUEUE, [])
        if pending and self.consume == 'dead':
            self.redis['pastorai:webhooks:dead'] = pending
        elif pending and self.consume == 'none':
            self.redis[legacy.QUEUE] = pending

    def _term(self, container):
        wid = container.pop('wid')
        self.redis[legacy.HEARTBEAT] = 'stopped'
        self.redis.pop(legacy.LEASE + wid)
        if not self.leave_registry:
            self.redis[legacy.REGISTRY].discard(wid)
            if not self.redis[legacy.REGISTRY]:
                del self.redis[legacy.REGISTRY]
        container['State'] = dict(Running=False, ExitCode=self.term_exit)

    def _probe(self, container):
        args = container['Args']
        if args[:3] == ['-I', '-c', legacy.RUNTIME_PROBE]:
            assert container['HostConfig']['NetworkMode'] == 'none'
            assert args[3:] == [legacy.SOURCE_ROOT, json.dumps(["sys_platform == 'win32'"]),
                                json.dumps(sorted(FILES))]
            container['out'] = json.dumps(self.runtime) + '\n'
        else:
            assert args[:2] == ['-c', legacy.ENQUEUE_PROBE]
            if self.parse_ignores:
                envelope = dict(payload=json.loads(args[2]), attempts=0, claim_id=uuid.uuid4().hex)
                self.redis.setdefault(legacy.QUEUE, []).insert(0, json.dumps(envelope))
            container['out'] = 'enqueued\n' if self.parse_ignores else 'not-ignored\n'
        container['State'] = dict(Running=False, ExitCode=0)
        return '0'

    def _redis_cli(self, command, *args):
        value = self.redis.get(args[0]) if args else None
        if command == 'PING':
            return 'PONG'
        if command == 'KEYS':
            assert args == ('*',)
            if len(self.worker_ids) == 2 and self.late:
                self.keys_after_restart += 1
                if self.keys_after_restart == 2:  # 1ª leitura vê o ACK; a mudança vem depois
                    self.late(self.redis, self.worker_ids[-1])
            return '\n'.join(sorted(self.redis))
        if command == 'GET':
            return value if isinstance(value, str) else ''
        if command == 'SMEMBERS':
            return '\n'.join(sorted(value or ()))
        if command == 'LRANGE':
            return '\n'.join(value or [])
        raise AssertionError(command)


def rehearsal(fake, **kwargs):
    now = [0.0]
    return legacy.QueueRehearsal(legacy_image=LEGACY, redis_image=REDIS, files=FILES, runner=fake,
                                 clock=lambda: now[0], sleep=lambda s: now.__setitem__(0, now[0] + s),
                                 **kwargs)


def refused(code, action):
    with pytest.raises(containment.Refused) as exc:
        action()
    assert str(exc.value) == code


# -- fonte legada --------------------------------------------------------
def blob_id(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


TREE = {
    'backend/app/__init__.py': ('100644', 'blob', b''),
    'backend/app/workers/queue_worker.py': ('100644', 'blob', b'# legado\n'),
    'backend/requirements.lock': ('100644', 'blob', LOCK.encode()),
    'backend/app/.env': ('100644', 'blob', b'PROTEGIDO'),
    'backend/app/.hidden.py': ('100644', 'blob', b'PROTEGIDO-1'),
    'backend/app/data/dump.sql': ('100644', 'blob', b'PROTEGIDO-2'),
    'backend/app/settings.json': ('100644', 'blob', b'PROTEGIDO-3'),
    'backend/scripts/clerk_sync.py': ('100644', 'blob', b'PROTEGIDO-4'),
    'backend/.env': ('100644', 'blob', b'PROTEGIDO-5'),
}


def fake_git(tree, calls, *, sha=legacy.LEGACY_SHA, tamper=False):
    blobs = {blob_id(data): data for _, _, data in tree.values()}

    def runner(argv):
        calls.append(argv)
        assert argv[:2] == ['-C', 'repo'] and argv[2] in {'rev-parse', 'ls-tree', 'cat-file'}
        if argv[2] == 'rev-parse':
            return (sha + '\n').encode()
        if argv[2] == 'ls-tree':
            # Pior caso: devolve a árvore inteira, ignorando o pathspec.
            return b''.join(f'{m} {k} {blob_id(d)}\t{p}'.encode() + b'\0' for p, (m, k, d) in tree.items())
        return blobs[argv[-1]] + (b'x' if tamper else b'')
    return runner


def test_materialize_writes_only_tracked_app_py_and_lock(tmp_path):
    calls = []
    out = tmp_path / 'legacy'
    entries = legacy.materialize('repo', out, fake_git(TREE, calls))
    written = sorted(str(p.relative_to(out)) for p in out.rglob('*') if p.is_file())
    assert written == sorted(FILES) and entries == legacy.manifest(FILES)
    assert (out / 'requirements.lock').read_text() == LOCK
    read = {c[-1] for c in calls if c[2] == 'cat-file'}
    assert read == {blob_id(TREE['backend/' + rel][2]) for rel in FILES}  # protegidos nunca lidos
    assert calls[0][-1] == legacy.LEGACY_SHA + '^{commit}'
    assert not any('archive' in c or 'checkout' in c for c in calls)
    refused('out-exists', lambda: legacy.materialize('repo', out, fake_git(TREE, [])))


